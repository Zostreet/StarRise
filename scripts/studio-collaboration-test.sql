-- Run against the development/production project with an administrative SQL connection.
-- All synthetic accounts, profiles, subscriptions, comments, and storage metadata roll back.
begin;
do $$
declare v_id uuid; v_role text;
begin
  foreach v_role in array array['owner','editor','viewer','stranger'] loop
    v_id:=gen_random_uuid();
    perform set_config('studio_test.'||v_role,v_id::text,true);
    insert into auth.users(id,raw_user_meta_data) values(v_id,jsonb_build_object('display_name','Studio access test '||v_role));
  end loop;
end $$;
set local role authenticated;
do $$
declare owner uuid:=current_setting('studio_test.owner')::uuid;
  editor uuid:=current_setting('studio_test.editor')::uuid;
  viewer uuid:=current_setting('studio_test.viewer')::uuid;
  stranger uuid:=current_setting('studio_test.stranger')::uuid;
  session uuid; second_session uuid; version uuid; path text; bad_version uuid; count_rows integer; denied boolean;
begin
  perform set_config('request.jwt.claims',json_build_object('sub',owner,'role','authenticated','is_anonymous',false)::text,true);
  session:=public.studio_create_session('Studio access test','transaction rollback');
  second_session:=public.studio_create_session('Other session','');
  perform public.studio_invite_member(session,editor,'editor');
  perform public.studio_invite_member(session,viewer,'viewer');
  select version_id,asset_path into version,path from public.studio_reserve_version(session,'Owner version','',12);
  denied:=false;
  begin perform public.studio_finish_version(version); exception when others then denied:=true; end;
  if not denied then raise exception 'Incomplete uploads must not publish'; end if;
  insert into storage.objects(bucket_id,name,metadata) values('studio-sessions',path,'{"size":12,"mimetype":"application/json"}'::jsonb);
  perform public.studio_finish_version(version);
  perform public.studio_add_comment(session,'Owner note',version);
  perform set_config('request.jwt.claims',json_build_object('sub',editor,'role','authenticated','is_anonymous',false)::text,true);
  if not exists(select 1 from public.studio_sessions where id=session) then raise exception 'Invitation metadata missing'; end if;
  if exists(select 1 from public.studio_versions where id=version) or exists(select 1 from storage.objects where bucket_id='studio-sessions' and name=path) or exists(select 1 from public.studio_comments where session_id=session) then raise exception 'Unaccepted invitation leaked content'; end if;
  denied:=false;
  begin perform public.studio_reserve_version(session,'Before acceptance','',12); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'Unaccepted editor published'; end if;
  perform public.studio_respond_invite(session,true);
  if not exists(select 1 from storage.objects where bucket_id='studio-sessions' and name=path) then raise exception 'Accepted editor cannot read'; end if;
  perform public.studio_add_comment(session,'Editor note',version);
  select version_id into bad_version from public.studio_reserve_version(session,'Editor work','',12,version);
  perform public.studio_cancel_version(bad_version);
  denied:=false;
  begin perform public.studio_reserve_version(second_session,'Wrong session','',12,version); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'Editor crossed session boundary'; end if;
  denied:=false;
  begin perform public.studio_invite_member(session,stranger,'editor'); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'Editor invited another member'; end if;
  update storage.objects set metadata='{"size":13}' where bucket_id='studio-sessions' and name=path;
  get diagnostics count_rows=row_count;
  if count_rows<>0 then raise exception 'Published asset was mutable'; end if;
  perform set_config('request.jwt.claims',json_build_object('sub',viewer,'role','authenticated','is_anonymous',false)::text,true);
  perform public.studio_respond_invite(session,true);
  if not exists(select 1 from public.studio_versions where id=version) then raise exception 'Viewer cannot read'; end if;
  perform public.studio_add_comment(session,'Viewer note',version);
  denied:=false;
  begin perform public.studio_reserve_version(session,'Viewer work','',12); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'Viewer published'; end if;
  denied:=false;
  begin insert into public.studio_sessions(owner_id,name) values(viewer,'Bypass RPC'); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'Direct mutation bypassed controls'; end if;
  perform set_config('request.jwt.claims',json_build_object('sub',stranger,'role','authenticated','is_anonymous',false)::text,true);
  if exists(select 1 from public.studio_sessions where id=session) or exists(select 1 from public.studio_versions where id=version) or exists(select 1 from storage.objects where bucket_id='studio-sessions' and name=path) then raise exception 'Stranger read session'; end if;
  denied:=false;
  begin insert into storage.objects(bucket_id,name,metadata) values('studio-sessions',session::text||'/'||gen_random_uuid()::text||'.json','{}'); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'Unreserved upload allowed'; end if;
  perform set_config('request.jwt.claims',json_build_object('sub',owner,'role','authenticated','is_anonymous',true)::text,true);
  denied:=false;
  begin perform public.studio_create_session('Anonymous bypass',''); exception when insufficient_privilege then denied:=true; end;
  if not denied or exists(select 1 from public.studio_versions where id=version) then raise exception 'Anonymous account got studio access'; end if;
  perform set_config('request.jwt.claims',json_build_object('sub',owner,'role','authenticated','is_anonymous',false)::text,true);
  perform public.studio_remove_member(session,editor);
  select version_id into bad_version from public.studio_reserve_version(second_session,'Second owner version','',12);
  denied:=false;
  begin perform public.studio_reserve_version(second_session,'Cross-session base','',12,version); exception when others then denied:=true; end;
  if not denied then raise exception 'Cross-session base version allowed'; end if;
  denied:=false;
  begin perform public.studio_reserve_version(session,'Oversize','',52428801); exception when check_violation then denied:=true; end;
  if not denied then raise exception 'Oversize snapshot allowed'; end if;
  perform set_config('request.jwt.claims',json_build_object('sub',editor,'role','authenticated','is_anonymous',false)::text,true);
  if exists(select 1 from public.studio_versions where id=version) or exists(select 1 from storage.objects where bucket_id='studio-sessions' and name=path) then raise exception 'Removed editor can still read'; end if;
  denied:=false;
  begin perform public.studio_reserve_version(session,'Removed work','',12); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'Removed editor published'; end if;
  raise notice 'PASS: owner/editor/viewer/invited/removed/stranger/anonymous, immutable assets, reserved uploads, size and session boundaries';
end $$;
reset role;
rollback;
